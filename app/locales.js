  function resolveLocale(value) {
    const code=String(value||'en-GB').replaceAll('_','-').toLowerCase();
    if(code.startsWith('zh'))return /hant|tw|hk|mo/.test(code)?'zh-Hant':'zh-Hans';
    if(code.startsWith('ja'))return 'ja';
    if(code.startsWith('es'))return 'es';
    if(code.startsWith('fr'))return 'fr';
    return 'en-GB';
  }
  function translate(locale,key,values={}) {
    const text=messages[resolveLocale(locale)][key]||messages['en-GB'][key]||key;
    return text.replace(/\{(\w+)\}/g,(_,name)=>String(values[name]??'{'+name+'}'));
  }
  function localizeError(locale,error) {
    if(error.key)return translate(locale,error.key,error.values);
    if(Object.values(messages[resolveLocale(locale)]).includes(error.message))return error.message;
    const entry=Object.entries(messages['en-GB']).find(([,text])=>text===error.message);
    if(entry)return translate(locale,entry[0]);
    const dimensions=/1536 × (\d+).*8 × (\d+)/.exec(error.message||'');
    if(dimensions)return translate(locale,'imageDimensions',{height:dimensions[1],rows:dimensions[2]});
    return translate(locale,error.code&&/^(EACCES|ENOENT|EPERM|ENOSPC|EISDIR|ENOTDIR)$/.test(error.code)?'fileError':'genericError');
  }
